"""Database operations and the ownership rule for tutor profiles. The routes
call these functions; the routes themselves contain no database code."""

from dataclasses import dataclass

from sqlalchemy import Select, String, cast, func, or_, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from peerora.core.permissions import Permission, has_permission
from peerora.models import Tutor, User
from peerora.schemas import TutorIn


class DuplicateStudentIdError(Exception):
    """Another tutor already uses this University Student ID."""


class TutorProfileExistsError(Exception):
    """The user already owns a tutor profile (only one is allowed)."""


@dataclass
class TutorFilters:
    q: str | None = None  # name, headline or department contains this text
    subject: str | None = None
    department: str | None = None
    teaching_mode: str | None = None


def _filtered(filters: TutorFilters) -> Select:
    statement = select(Tutor)
    if filters.q:
        pattern = f"%{filters.q.strip().lower()}%"
        statement = statement.where(
            or_(
                func.lower(Tutor.full_name).like(pattern),
                func.lower(Tutor.headline).like(pattern),
                func.lower(Tutor.department).like(pattern),
                func.lower(cast(Tutor.subjects, String)).like(pattern),
            )
        )
    if filters.subject:
        # subjects is a JSON list; matching the quoted name works in both
        # PostgreSQL (JSONB cast to text) and SQLite (JSON stored as text).
        statement = statement.where(cast(Tutor.subjects, String).like(f'%"{filters.subject}"%'))
    if filters.department:
        statement = statement.where(Tutor.department == filters.department)
    if filters.teaching_mode:
        statement = statement.where(Tutor.teaching_mode == filters.teaching_mode)
    return statement


def list_tutors(
    db: Session, filters: TutorFilters | None = None, limit: int | None = None, offset: int = 0
) -> tuple[list[Tutor], int]:
    """Matching tutors, newest first, plus the total number of matches."""
    statement = _filtered(filters or TutorFilters())
    total = db.scalar(select(func.count()).select_from(statement.subquery())) or 0
    page = statement.order_by(Tutor.id.desc()).offset(offset)
    if limit is not None:
        page = page.limit(limit)
    return list(db.scalars(page)), total


def get_tutor_by_user(db: Session, user_id: int) -> Tutor | None:
    return db.scalar(select(Tutor).where(Tutor.user_id == user_id))


def can_manage(user: User | None, tutor: Tutor) -> bool:
    """Ownership rule: the owner, or an administrator acting as moderator.
    Profiles without an owner (created before accounts existed) are admin-only."""
    if user is None:
        return False
    if tutor.user_id is not None and tutor.user_id == user.id:
        return True
    return has_permission(user.role, Permission.CONTENT_MODERATE)


def get_tutor(db: Session, tutor_id: int) -> Tutor | None:
    return db.get(Tutor, tutor_id)


def _student_id_taken(
    db: Session, student_id: str, exclude_id: int | None = None
) -> bool:
    """Is the Student ID used by any tutor (other than exclude_id)?"""
    statement = select(Tutor.id).where(Tutor.student_id == student_id)
    if exclude_id is not None:
        statement = statement.where(Tutor.id != exclude_id)
    return db.scalar(statement.limit(1)) is not None


def _commit(db: Session, student_id: str, exclude_id: int | None = None) -> None:
    """Save the changes. If the database rejects them because of a duplicate
    Student ID (for example two requests at the same moment), report that
    clearly; any other database problem is raised unchanged."""
    try:
        db.commit()
    except IntegrityError:
        db.rollback()
        if _student_id_taken(db, student_id, exclude_id):
            raise DuplicateStudentIdError from None
        raise


def create_tutor(db: Session, data: TutorIn, user_id: int) -> Tutor:
    """Create the profile for user_id (taken from the access token, never the body)."""
    if get_tutor_by_user(db, user_id) is not None:
        raise TutorProfileExistsError
    if _student_id_taken(db, data.student_id):
        raise DuplicateStudentIdError
    tutor = Tutor(**data.model_dump(), user_id=user_id)
    db.add(tutor)
    _commit(db, data.student_id)
    db.refresh(tutor)  # loads the id and timestamps generated by the database
    return tutor


def update_tutor(db: Session, tutor_id: int, data: TutorIn) -> Tutor | None:
    """Replace every field of a tutor. Returns None if the tutor does not exist."""
    tutor = db.get(Tutor, tutor_id)
    if tutor is None:
        return None
    if _student_id_taken(db, data.student_id, exclude_id=tutor_id):
        raise DuplicateStudentIdError
    for field, value in data.model_dump().items():
        setattr(tutor, field, value)
    _commit(db, data.student_id, exclude_id=tutor_id)
    db.refresh(tutor)
    return tutor


def delete_tutor(db: Session, tutor_id: int) -> bool:
    """Delete one tutor by id. Returns False if it does not exist."""
    tutor = db.get(Tutor, tutor_id)
    if tutor is None:
        return False
    db.delete(tutor)
    db.commit()
    return True