"""Database operations for tutors. The routes call these functions; the routes
themselves contain no database code."""

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from peerora.models import Tutor
from peerora.schemas import TutorIn


class DuplicateStudentIdError(Exception):
    """Another tutor already uses this University Student ID."""


def list_tutors(db: Session) -> list[Tutor]:
    """All tutors, newest first."""
    return list(db.scalars(select(Tutor).order_by(Tutor.id.desc())))


def get_tutor(db: Session, tutor_id: int) -> Tutor | None:
    return db.get(Tutor, tutor_id)


def _student_id_taken(
    db: Session, student_id: str, exclude_id: int | None = None
) -> bool:
    """Is the Student ID used by any tutor (other than exclude_id)?"""
    statement = select(Tutor.id).where(Tutor.student_id == student_id)
    if exclude_id is not None:
        statement = statement.where(Tutor.id != exclude_id)
    return db.scalar(statement.limit(1)) is not None


def _commit(db: Session, student_id: str, exclude_id: int | None = None) -> None:
    """Save the changes. If the database rejects them because of a duplicate
    Student ID (for example two requests at the same moment), report that
    clearly; any other database problem is raised unchanged."""
    try:
        db.commit()
    except IntegrityError:
        db.rollback()
        if _student_id_taken(db, student_id, exclude_id):
            raise DuplicateStudentIdError from None
        raise


def create_tutor(db: Session, data: TutorIn) -> Tutor:
    if _student_id_taken(db, data.student_id):
        raise DuplicateStudentIdError
    tutor = Tutor(**data.model_dump())
    db.add(tutor)
    _commit(db, data.student_id)
    db.refresh(tutor)  # loads the id and timestamps generated by the database
    return tutor


def update_tutor(db: Session, tutor_id: int, data: TutorIn) -> Tutor | None:
    """Replace every field of a tutor. Returns None if the tutor does not exist."""
    tutor = db.get(Tutor, tutor_id)
    if tutor is None:
        return None
    if _student_id_taken(db, data.student_id, exclude_id=tutor_id):
        raise DuplicateStudentIdError
    for field, value in data.model_dump().items():
        setattr(tutor, field, value)
    _commit(db, data.student_id, exclude_id=tutor_id)
    db.refresh(tutor)
    return tutor


def delete_tutor(db: Session, tutor_id: int) -> bool:
    """Delete one tutor by id. Returns False if it does not exist."""
    tutor = db.get(Tutor, tutor_id)
    if tutor is None:
        return False
    db.delete(tutor)
    db.commit()
    return True